export type IconName = keyof typeof BITMAPS

export function icon(name: IconName, cls = ''): string {
  const rows = BITMAPS[name]
  const rects = rows.flatMap((row, y) => [...row].map((c, x) => (c === '#' ? `<rect x="${x}" y="${y}" width="1" height="1"/>` : ''))).join('')
  return `<svg class="icon ${cls}" viewBox="0 0 7 7" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects}</svg>`
}
